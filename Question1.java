public class Question1 {
    public static void main(String[] args){
          // Start countdown at 10
        int number = 10;

          // Count down until 1
        while (number >= 1){
            System.out.println(number);
            number --;
        }
        // Print after the loop ends
        System.out.println("Liftoff!");
    }
}